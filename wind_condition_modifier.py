def apply_wind_modifier(venue: str, course: int, wind_direction: str, wind_speed: float, base_score: float) -> float:
    """
    風向と風速、競艇場、コースから倍率を算出し、既存スコアを補正する。
    倍率 = 現在の風況での勝率 / 無風時の勝率
    """
    venue_data = WIND_WIN_RATES.get(venue)
    if not venue_data:
        return base_score
        
    course_data = venue_data.get(course)
    if not course_data:
        return base_score

    # 1. 風況カテゴリの判定
    if wind_speed >= 5.0:
        category = "強風"
    elif 2.0 <= wind_speed <= 4.0:
        # 風向文字から追い風・向かい風を判定（app.pyの表記に合わせる）
        # 追い風：南系
        # 向かい風：北系
        is_tailwind = "追い風" in wind_direction or any(d in wind_direction for d in ["南", "南東", "南南東", "南南西", "南西"])
        is_headwind = "向かい風" in wind_direction or any(d in wind_direction for d in ["北", "北西", "北北西", "北北東", "北東"])
        
        if is_tailwind:
            category = "追い風"
        elif is_headwind:
            category = "向かい風"
        else:
            category = "無風" # 横風2-4mなどの場合は無風と同等（倍率1.0）
    else:
        category = "無風" # 0-1mは無風

    # 2. 勝率の抽出
    current_rate = course_data.get(category, 0.0)
    no_wind_rate = course_data.get("無風", 0.0)

    # 3. ゼロ除算回避と倍率計算
    if no_wind_rate == 0.0 or current_rate == 0.0:
        multiplier = 1.0
    else:
        multiplier = current_rate / no_wind_rate

    return base_score * multiplier
